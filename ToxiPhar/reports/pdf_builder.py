from reportlab.lib.pagesizes import A4
from reportlab.platypus import SimpleDocTemplate, Table, Paragraph, Spacer, Image
from reportlab.lib.styles import getSampleStyleSheet
from rdkit import Chem
import io

# RDKit's Draw module needs a system DLL that isn't available on this
# machine right now. Rather than crash the whole app over a cosmetic
# feature, we detect it once here and skip the molecule image if it's
# unavailable — the report still generates with all prediction data.
try:
    from rdkit.Chem import Draw
    DRAW_AVAILABLE = True
except ImportError:
    DRAW_AVAILABLE = False
    print("WARNING: rdkit.Chem.Draw unavailable — PDF reports will skip the molecule image.")


def build_report(result: dict) -> bytes:
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4)
    styles = getSampleStyleSheet()
    elements = []

    elements.append(Paragraph("ADMET Toxicity Prediction Report", styles["Title"]))
    elements.append(Paragraph(f"SMILES: {result['smiles_cleaned']}", styles["Normal"]))
    elements.append(Spacer(1, 12))

    if DRAW_AVAILABLE:
        mol = Chem.MolFromSmiles(result["smiles_cleaned"])
        img_path = "/tmp/mol_temp.png"
        Draw.MolToFile(mol, img_path, size=(300, 300))
        elements.append(Image(img_path, width=200, height=200))
        elements.append(Spacer(1, 12))
    else:
        elements.append(Paragraph(
            "(Molecule structure image unavailable in this environment.)",
            styles["Italic"]
        ))
        elements.append(Spacer(1, 12))

    data = [["Endpoint", "Probability", "Predicted class"]]
    for endpoint, d in result["predictions"].items():
        data.append([endpoint, str(d["probability"]), str(d["predicted_class"])])
    elements.append(Table(data))
    elements.append(Spacer(1, 12))

    elements.append(Paragraph(
        "Disclaimer: predictions generated by production CatBoost models trained "
        "on 100% of available data without a held-out test split for final fit. "
        "See accompanying benchmark file for validated performance metrics.",
        styles["Italic"]
    ))

    doc.build(elements)
    buffer.seek(0)
    return buffer.getvalue()